a = 17
b = 5

print("Addition:      ", a + b)    # 22
print("Subtraction:   ", a - b)    # 12
print("Multiplication:", a * b)    # 85
print("Division:      ", a / b)    # 3.4  (always a float)
print("Floor division:", a // b)   # 3    (drops the decimal)
print("Modulus:       ", a % b)    # 2    (the remainder)
print("Exponent:      ", a ** 2)   # 289  (a squared)

# update a variable using its own value
total = 10
total += 5    # same as total = total + 5
print("Total:", total)